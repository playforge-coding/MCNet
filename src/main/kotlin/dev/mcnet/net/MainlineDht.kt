package dev.mcnet.net

import computer.iroh.EndpointBuilder
import dev.mcnet.MCNet

/**
 * Attaches iroh's BitTorrent Mainline DHT address lookup to an endpoint, when
 * the bindings on the classpath expose it.
 *
 * Reached reflectively, deliberately. The published `computer.iroh:iroh`
 * artifact does not ship `DhtAddressLookup`; it only exists in the bindings
 * the build generates from a patched iroh-ffi (see `dht/build.sh` in this
 * repository). A build without cargo falls back to the published bindings,
 * and reflection means the same source compiles and runs against either.
 *
 * The signatures below are generated by UniFFI from the patch, so they are
 * fixed by it rather than guessed:
 *
 *     class DhtAddressLookup(publish: Boolean, unfiltered: Boolean)
 *     fun EndpointBuilder.addressLookup(lookup: DhtAddressLookup)
 */
object MainlineDht {
    private const val LOOKUP_CLASS = "computer.iroh.DhtAddressLookup"

    /** True when the bindings on the classpath carry DHT support. */
    val isAvailable: Boolean by lazy { lookupClass() != null }

    private fun lookupClass(): Class<*>? =
        runCatching { Class.forName(LOOKUP_CLASS, true, EndpointBuilder::class.java.classLoader) }
            .getOrNull()

    /**
     * Configures [builder] to resolve endpoint ids through the Mainline DHT.
     *
     * @param publish announce this endpoint's own address. Hosts want this;
     *   clients that only ever join should not add write traffic to the DHT.
     * @param unfiltered also publish direct IP addresses. Off by default, which
     *   publishes relay addresses only.
     * @return true if the lookup was attached; false if these bindings do not
     *   support it, in which case the endpoint keeps the preset's own resolver.
     */
    fun attach(
        builder: EndpointBuilder,
        publish: Boolean,
        unfiltered: Boolean = false,
    ): Boolean {
        val cls =
            lookupClass() ?: run {
                MCNet.logger.warn(
                    "addressLookup=dht was requested, but these iroh bindings have no {}. " +
                        "Falling back to the preset's resolver. This jar was built without " +
                        "the DHT patch; see dht/README.md.",
                    LOOKUP_CLASS,
                )
                return false
            }

        return runCatching {
            val lookup =
                cls
                    .getConstructor(Boolean::class.javaPrimitiveType, Boolean::class.javaPrimitiveType)
                    .newInstance(publish, unfiltered)

            EndpointBuilder::class.java
                .getMethod("addressLookup", cls)
                .invoke(builder, lookup)

            MCNet.logger.info("resolving endpoint ids over the Mainline DHT (publish={})", publish)
            true
        }.onFailure {
            // A signature mismatch means the bindings were built from a
            // different patch than the one this mod expects; say so plainly
            // rather than failing later with something cryptic.
            MCNet.logger.error(
                "found {} but could not attach it. Were these bindings built from dht/build.sh?",
                LOOKUP_CLASS,
                it,
            )
        }.getOrDefault(false)
    }
}
